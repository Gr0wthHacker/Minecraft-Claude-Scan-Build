package dev.jack.chunkscan;

import org.junit.jupiter.api.Test;

import java.util.List;
import java.util.Map;

import static org.junit.jupiter.api.Assertions.*;

/**
 * The three things both languages have to agree about, and the one ordering nothing expressed.
 *
 * <p>All four were written twice - once here and once in Python - and all four had drifted. The
 * item map cost 7,965 cells of the park, reported as unobtainable raw material because no chest
 * has ever held an item called `oak_wall_sign`. The property sets differed by four, so 147 cells
 * could never match and `placementComplete()` was never true. And 2,970 cells were on the dig list
 * AND in the block list with nothing to say which came first, so an unattended session could place
 * a block and break it again for ever.
 */
class IdentityAndOrderTest {

	@Test
	void theShippedItemMapIsWhatPlacesTheBlock() {
		// FROM THE FILE, not from the fallback: the map is generated by tools/export_rules.py from
		// mcbuild/items.py, and this is the half of "one source" that proves the jar reads it.
		assertEquals("oak_sign", Rules.itemFor("oak_wall_sign"));
		assertEquals("water_bucket", Rules.itemFor("water"));
		assertEquals("redstone", Rules.itemFor("redstone_wire"));
		assertEquals("cauldron", Rules.itemFor("water_cauldron"));
		assertNull(Rules.itemFor("stone"), "a block that IS its own item is not in the exception map");
	}

	@Test
	void itemForPrefersTheMapAndStillAnswersWithoutIt() {
		assertEquals("oak_sign", ActionRecipe.itemFor("minecraft:oak_wall_sign[facing=east]"));
		assertEquals("stone_bricks", ActionRecipe.itemFor("minecraft:stone_bricks"));
	}

	@Test
	void theShippedPropertySetsAreThePythonOnes() {
		// DECIDED and COMPLETE are two questions on the Python side and one here: `role` only ever
		// asks whether a property must MATCH, so it takes the union. The split matters where the
		// cell strings are written, which is the other side.
		assertTrue(Rules.intentional().contains("facing"), "a decision");
		assertTrue(Rules.intentional().contains("waterlogged"), "a completion requirement");
		assertFalse(Rules.intentional().contains("shape"), "a stair's shape is the game's");
		assertTrue(Rules.multiface().contains("vine"));
	}

	@Test
	void aDerivedPropertyIsNeverRequired() {
		assertEquals(StateContract.Role.REQUIRED, StateContract.role("oak_stairs", "facing"));
		assertEquals(StateContract.Role.DERIVED, StateContract.role("oak_stairs", "shape"));
		assertEquals(StateContract.Role.DERIVED, StateContract.role("chest", "type"));
		assertEquals(StateContract.Role.REQUIRED, StateContract.role("powered_rail", "shape"));
	}

	@Test
	void anOpenTrapdoorIsHandedBackRatherThanRetriedForEver() {
		// A door places SHUT, so `open=true` can never match however many times it is tried - and
		// that is not a stall, it is a design that can never finish. 147 such cells kept `todo`
		// non-empty for ever and `follow all` never moved on.
		assertNotNull(ActionRecipe.manual("minecraft:oak_trapdoor[open=true,facing=north]"));
		assertNull(ActionRecipe.manual("minecraft:oak_trapdoor[open=false,facing=north]"));
		assertNull(ActionRecipe.manual("minecraft:stone_bricks"));
	}

	@Test
	void aDoorIsOneItemAndADoubleSlabIsTwo() {
		// Wrong in BOTH directions before: a door and a bed asked for twice what they need, and a
		// double slab asked for half - one sends you shopping for what you have, the other sends
		// you back for what you ran out of.
		assertTrue(Work.secondHalf("minecraft:oak_door[half=upper,facing=north]"));
		assertTrue(Work.secondHalf("minecraft:red_bed[part=head,facing=north]"));
		assertFalse(Work.secondHalf("minecraft:oak_door[half=lower,facing=north]"));
		assertTrue(Work.doubleSlab("minecraft:oak_slab[type=double]"));
		assertFalse(Work.doubleSlab("minecraft:oak_slab[type=top]"));
	}

	@Test
	void aTallyCountsItemsRatherThanCells() {
		var lower = new Work.Cell(new net.minecraft.core.BlockPos(0, 0, 0),
			"minecraft:oak_door[half=lower,facing=north]");
		var upper = new Work.Cell(new net.minecraft.core.BlockPos(0, 1, 0),
			"minecraft:oak_door[half=upper,facing=north]");
		var dbl = new Work.Cell(new net.minecraft.core.BlockPos(1, 0, 0),
			"minecraft:oak_slab[type=double]");
		Map<String, Integer> t = Work.tally(List.of(lower, upper, dbl));
		assertEquals(1, t.get("oak_door"), "two cells, one door");
		assertEquals(2, t.get("oak_slab"), "one cell, two slabs");
	}

	@Test
	void aWrittenOffPlaceComesBack() {
		// IT HAD NO EXPIRY, and two of the three paths that strike it are not about the place: a
		// search that runs out of its millisecond budget returns the same empty list as one that
		// proved there is no way through, so two slow ticks deleted an eight-block cube of the
		// park for the rest of the session with nothing but undone work to say so.
		assertTrue(Ignored.FORGET_MS > 0, "a strike must be able to expire");
		assertTrue(Ignored.FORGET_MS >= 60_000, "...but not so fast that a real dead end is retried");
	}

	@Test
	void aDriftingDestinationIsTheSameDestination() {
		// A station re-centres on the cells still to place, so the target moves a block or two on
		// EVERY recount. Compared with equals, that zeroed the recovery ladder twice a second and
		// the whole escalation was dead code in the one mode it was written for.
		assertTrue(Autopilot.SAME_TARGET >= 2.0, "a couple of blocks of drift is not a new place");
		assertTrue(Autopilot.SAME_TARGET < Loop.VICINITY,
			"...and it must be smaller than the working radius, or two real spots become one");
	}
}
